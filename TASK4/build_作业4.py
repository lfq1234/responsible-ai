add_para_md(
    "**单独使用 PDP 的误导性：**PDP 把两个子群体的曲线平均，两条方向相反的曲线在平均后可能接近平坦或仅呈"
    "弱效应，看起来“变更规模对缺陷风险几乎无影响”。但这不代表任何真实个体经历过该平均效应——模型实际对"
    "新模块的大规模变更是强正向、对维护模块是弱负向的。若验证人员据此做特征取舍或风险分级，会错误低估新"
    "模块大规模变更的缺陷风险，甚至误删有用特征。"
)
add_para_md(
    "**叠加 ICE 曲线能揭示什么：**ICE 为每个观测样本画一条“保持其他特征不变、预测随 LOC 变化”的曲线，"
    "PDP 正是所有 ICE 曲线的平均。把 ICE 叠加在 PDP 之上，可以清楚看到**两个方向相反的曲线簇**——新模块"
    "的 ICE 普遍陡峭上升、维护模块的 ICE 平坦或下降，而 PDP 的平均线正是把这两个簇抵消后的结果。审查者"
    "据此识别异质性，进而按子群体分别建模或分群评估风险，而不是信任单条平均曲线。"
)

