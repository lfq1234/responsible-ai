add_heading("b. 相关预测变量场景：为何单独打乱会产生误导", 2)
add_para_md(
    "**场景：**特征“**代码行数（LOC）**”与“**圈复杂度**”高度相关——一个模块的行数越多，其分支结构与圈"
    "复杂度往往也越高，二者同为代码规模/复杂度的度量，现实中几乎必然正相关。"
)
add_para_md(
    "PFI 打乱某列时隐含假设该列与其他列独立，但 LOC 与圈复杂度并不独立。单独打乱 LOC 后，数据中会出现"
    "大量现实中几乎不存在的组合（例如“超大代码量+极低圈复杂度”，或“极小代码量+极高复杂度”），模型在这些"
    "不现实的组合上评分会显著劣化。于是："
)
add_bullet(
    "若模型真正依赖的是圈复杂度，打乱 LOC 造成的误差上升，主要来自“生成了不现实组合”而非“模型独立依赖"
    " LOC”，LOC 的重要性分数被**高估**，成为打乱操作本身的产物；"
)
add_bullet(
    "反过来，打乱 LOC 时模型仍可部分依靠未被打乱的圈复杂度维持表现，LOC 的真实边际贡献可能被**低估**。"
)
add_para_md(
    "无论哪个方向，单独打乱一个相关变量得到的分数，反映的都是“打乱操作与相关结构的相互作用”，而非该特征"
    "的真实边际贡献——这正是讲义所指出的“重要性分数可能只是打乱操作的产物”。因此，解释 PFI 时必须先检查"
    "特征相关性，必要时对相关特征组整体打乱（组置换），并注意 PFI 只能回答“是否重要”，不能回答“如何、"
    "朝哪个方向、在什么范围内影响预测”。"
)

